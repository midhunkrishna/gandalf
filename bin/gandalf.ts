/** git's well-known empty-tree object — the diff base for root commits. */
const EMPTY_TREE = "4b825dc642cb6eb9a060e54bf8d69288fbee4904";

/** Per-file pass cache lives beside the lesson store (never in the analyzed repo). */
function passCacheDir(storeDir: string): string {
  return join(storeDir, "pass-cache");
}

/**
 * Shared per-invocation store resolution: repo root + user config + --out-dir
 * override. Config warnings surface once, on stderr, without failing the run.
 */
async function resolveStore(
  opts: { cwd: string; outDir?: string },
): Promise<ResolvedStore & { cwd: string; config: GandalfConfig }> {
  const cwd = await repoRoot(resolve(opts.cwd));
  const { config, warnings } = await loadConfig();
  for (const w of warnings) process.stderr.write(`gandalf: ${w}\n`);
  const store = await resolveLessonsDir(cwd, config, opts.outDir);
  if (store.source === "project-wd (empty repo fallback)") {
    process.stderr.write("gandalf: repository has no commits yet — using <repo>/.gandalf/lessons\n");
  }
  return { cwd, config, ...store };
}

/** Run `vite build` (with injection env) from the gandalf project root. */
function runViteBuild(projectRoot: string, env: Record<string, string>): Promise<void> {
  return new Promise((res, rej) => {
    const child = spawn("npx", ["vite", "build"], {
      cwd: projectRoot,
      env: { ...process.env, ...env },
      stdio: "inherit",
    });
    child.on("error", rej);
    child.on("close", (code) => (code === 0 ? res() : rej(new Error(`vite build exited ${code}`))));
  });
}

const program = new Command();

program
  .name("gandalf")
  .description("Teaches the code changes behind each commit/ticket — generated by Claude Code.")
  .option("--log-level <level>", "debug | info | warn | error (watch defaults to debug)")
  .version("0.0.0");

/** Effective log level: explicit flag wins; `fallback` is the command's default. */
function logLevel(fallback: LogLevel): LogLevel {
  const flag = program.opts().logLevel as string | undefined;
  return flag && isLogLevel(flag) ? flag : fallback;
}

program
  .command("generate")
  .description("Analyze a diff and write a lesson bundle (default: HEAD vs working tree).")
  .option("--from <ref>", "base ref", "HEAD")
  .option("--to <ref>", "target ref (omit for the uncommitted working tree)")
  .option("--ticket <id>", "force a ticket id for the intent overlay")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (overrides the configured lesson location)")
  .option("--lite", "cheap profile: haiku file passes + one merged synthesis pass")
  .option("--full", "every lens, opus synthesis (the default for generate)")
  .option("--model-file <model>", "model for per-file passes (overrides the profile)")
  .option("--model-synth <model>", "model for the synthesis pass (overrides the profile)")
  .option("--concurrency <n>", "parallel per-file passes", "4")
  .option("--no-cache", "run every per-file pass live, ignoring the pass cache")
  .action(async (opts) => {
    const store = await resolveStore(opts);
    const { cwd, lessonsDir, config } = store;
    const profile = resolveProfile(opts, config.generation_profile, "full");
    const bundle = await generateLesson({
      cwd,
      fromRef: opts.from,
      toRef: opts.to, // undefined -> working tree
      ticketId: opts.ticket,
      modelFile: opts.modelFile,
      modelSynth: opts.modelSynth,
      concurrency: Number(opts.concurrency) || 4,
      profile,
      passCache: opts.cache === false ? undefined : new PassCache(passCacheDir(store.storeDir)),
      onProgress: (m) => process.stderr.write(`${m}\n`),
    });
    const file = await saveLesson(bundle, lessonsDir);
    process.stderr.write("\n");
    console.log(`Lesson: ${bundle.meta.title}`);
    console.log(`  verdict: ${bundle.meta.verdict}  breaking: ${bundle.meta.breakingCount}  profile: ${bundle.meta.profile}`);
    console.log(`  files: ${bundle.files.length}  contracts: ${bundle.contracts.length}`);
    console.log(`  saved: ${file}`);
  });

program
  .command("list")
  .description("List persisted lessons (newest first).")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (overrides the configured lesson location)")
  .action(async (opts) => {
    const { lessonsDir } = await resolveStore(opts);
    const metas = await listLessons(lessonsDir);
    if (!metas.length) {
      console.log("No lessons yet.");
      return;
    }
    for (const m of metas) {
      console.log(`${m.createdAt}  ${m.id}`);
      console.log(`    ${m.title}  [${m.verdict}${m.breakingCount ? `, ${m.breakingCount} breaking` : ""}]`);
    }
  });

program
  .command("doctor")
  .description("Cross-section integrity check of persisted lessons (graph↔files joins, evidence refs, …).")
  .option("--lesson <id>", "check one lesson (default: all)")
  .option("--fix", "apply the graph repairs to the stored lesson files (default: report only)")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (overrides the configured lesson location)")
  .action(async (opts) => {
    const store = await resolveStore(opts);
    const lessonsDir = store.lessonsDir;
    // Placement / config report first — the questions doctor gets asked most.
    const { config, path: cfgPath } = await loadConfig();
    console.log(`config: ${cfgPath}${existsSync(cfgPath) ? "" : " (absent — using defaults)"}`);
    console.log(`  lesson_location: ${config.lesson_location}`);
    console.log(
      `  generation_profile: ${config.generation_profile ?? "(unset: generate runs full, watch runs lite)"}`,
    );
    console.log(`  lessons dir: ${lessonsDir} (${store.source})`);
    const cache = await cacheStats(passCacheDir(store.storeDir));
    console.log(
      `  pass cache: ${passCacheDir(store.storeDir)} — ${cache.entries} entr${cache.entries === 1 ? "y" : "ies"}, ${(cache.bytes / (1024 * 1024)).toFixed(1)} MB`,
    );
    const metas = await listLessons(lessonsDir);
    const targets = opts.lesson ? metas.filter((m) => m.id === opts.lesson) : metas;
    if (!targets.length) {
      console.log(opts.lesson ? `No lesson "${opts.lesson}".` : "No lessons yet.");
      return;
    }
    let errors = 0;
    for (const m of targets) {
      const stored = await loadLesson(lessonsDir, m.id);
      console.log(`${m.id}`);
      // Graph repair is reported for every lesson but only written with --fix, so the
      // default stays non-destructive: the report says exactly what --fix would do.
      const repair = repairGraph(stored.graph);
      let lesson = stored;
      if (repair.actions.length) {
        for (const a of repair.actions) console.log(`  ${opts.fix ? "✎ fixed" : "→ would fix"}: ${a}`);
        if (opts.fix) {
          lesson = { ...stored, graph: repair.graph };
          await saveLesson(lesson, lessonsDir);
        } else {
          console.log("  (re-run with --fix to apply)");
        }
      }
      const issues = validateLesson(lesson);
      errors += issues.filter((i) => i.severity === "error").length;
      console.log(
        formatIssues(issues)
          .split("\n")
          .map((l) => `  ${l}`)
          .join("\n"),
      );
    }
    if (errors > 0) process.exitCode = 1;
  });

program
  .command("serve")
  .description("Serve the interactive viewer + lesson API.")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (overrides the configured lesson location)")
  .option("--port <n>", "port", "4173")
  .action(async (opts) => {
    const { lessonsDir } = await resolveStore(opts);
    if (!webBuilt()) {
      console.error("Viewer not built yet. Run: npm run build:web");
      process.exitCode = 1;
      return;
    }
    await startServer({ lessonsDir, port: Number(opts.port) || 4173 });
  });

program
  .command("build")
  .description("Export a self-contained, offline static HTML lesson (vite-plugin-singlefile).")
  .option("--lesson <id>", "lesson id to export (default: newest)")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (overrides the configured lesson location)")
  .requiredOption("--out <file>", "output HTML file path")
  .action(async (opts) => {
    const { lessonsDir } = await resolveStore(opts);
    const metas = await listLessons(lessonsDir);
    if (!metas.length) {
      console.error("No lessons to export. Run `gandalf generate` first.");
      process.exitCode = 1;
      return;
    }
    const id = opts.lesson ?? metas[0]!.id;
    const lesson = await loadLesson(lessonsDir, id);
    const out = resolve(opts.out);
    const done = () => {
      console.log(`Static lesson exported: ${out}`);
      console.log(`  lesson: ${lesson.meta.title} [${id}]`);
      console.log(`  open it directly in a browser — no server needed.`);
    };

    // Fast path: the prebuilt template shipped in the npm package (or built once
    // from source via build:template) — substitution only, no Vite at runtime.
    const projectRoot = resolve(import.meta.dirname, "..");
    const templateFile = join(projectRoot, "dist", "template", "index.html");
    if (existsSync(templateFile)) {
      process.stderr.write(`Exporting ${id} from the prebuilt template…\n`);
      const html = renderTemplate(await readFile(templateFile, "utf8"), lesson, metas);
      await mkdir(dirname(out), { recursive: true });
      await writeFile(out, html, "utf8");
      done();
      return;
    }

    // Source-checkout fallback: compile the export with Vite, lesson data injected.
    const stamp = Date.now();
    const lessonFile = join(tmpdir(), `gandalf-build-${stamp}.json`);
    const buildDir = join(tmpdir(), `gandalf-singlefile-${stamp}`);
    await writeFile(lessonFile, JSON.stringify({ lesson, lessons: metas }));

    process.stderr.write(`Building single-file export for ${id}…\n`);
    try {
      await runViteBuild(projectRoot, {
        GANDALF_LESSON_FILE: lessonFile,
        GANDALF_SINGLEFILE: "1",
        GANDALF_OUT_DIR: buildDir,
      });
      await mkdir(dirname(out), { recursive: true });
      await copyFile(join(buildDir, "index.html"), out);
      done();
    } finally {
      await rm(lessonFile, { force: true }).catch(() => {});
      await rm(buildDir, { recursive: true, force: true }).catch(() => {});
    }
  });

program
  .command("watch")
  .description("Foreground watcher: teach each new commit as it lands (orthogonal to your build).")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (overrides the configured lesson location)")
  .option("--once", "process the pending backlog, then exit")
  .option("--status", "print the watch journal summary and exit")
  .option("--from <ref>", "baseline when no journal exists yet (default: HEAD — teach future commits only)")
  .option("--retry-failed", "re-enqueue previously failed commits")
  .option("--max <n>", "cap commits processed per planning cycle")
  .option("--include-merges", "teach merge commits too (first-parent diff)")
  .option("--poll <ms>", "HEAD poll interval", "5000")
  .option("--debounce <ms>", "quiet period after HEAD moves before planning", "5000")
  .option("--no-infer-ticket", "do not parse a leading ticket id from commit subjects")
  .option("--lite", "cheap profile: haiku file passes + one merged synthesis pass (the default for watch)")
  .option("--full", "every lens, opus synthesis")
  .option("--model-file <model>", "model for per-file passes (overrides the profile)")
  .option("--model-synth <model>", "model for the synthesis pass (overrides the profile)")
  .option("--concurrency <n>", "parallel per-file passes", "4")
  .option("--no-cache", "run every per-file pass live, ignoring the pass cache")
  .action(async (opts) => {
    const log = createLogger(logLevel("debug"));
    const store = await resolveStore(opts);
    log.debug(`store: ${store.lessonsDir} (${store.source})`);

    if (opts.status) {
      const { journal, corrupt } = await loadJournal(store.storeDir);
      if (corrupt) log.warn(`journal was corrupt — moved aside to ${corrupt}`);
      if (!journal) {
        console.log("No watch journal yet — run `gandalf watch` (or --once) to start one.");
        return;
      }
      const recs = Object.entries(journal.commits);
      const count = (s: string) => recs.filter(([, r]) => r.status === s).length;
      console.log(`journal: ${store.storeDir}/watch-journal.json`);
      console.log(`  frontier: ${journal.lastProcessed.slice(0, 12)} (baseline ${journal.baseline.slice(0, 12)})`);
      console.log(`  done ${count("done")} · failed ${count("failed")} · skipped ${count("skipped")} · pending ${count("pending")}`);
      const failures = recs.filter(([, r]) => r.status === "failed").slice(-5);
      for (const [sha, r] of failures) {
        console.log(`  FAILED ${sha.slice(0, 12)} ${r.subject}`);
        console.log(`         ${r.error ?? ""}`);
      }
      if (count("failed") > 0) process.exitCode = 1;
      return;
    }

    // Watch defaults to lite (it teaches every commit, so volume decides). Log the
    // resolved profile so that default is never a silent surprise.
    const profile = resolveProfile(opts, store.config.generation_profile, "lite");
    log.info(`generation profile: ${profile}`);

    const lock = acquireLock(store.storeDir);
    if (!lock.acquired) {
      log.error(`another watcher holds this store (pid ${lock.holderPid ?? "?"}) — exiting`);
      process.exitCode = 1;
      return;
    }

    const runOpts: WatchRunOptions = {
      cwd: store.cwd,
      storeDir: store.storeDir,
      from: opts.from,
      pollMs: Number(opts.poll) || 5000,
      debounceMs: Number(opts.debounce) || 5000,
      plan: {
        includeMerges: Boolean(opts.includeMerges),
        retryFailed: Boolean(opts.retryFailed),
        max: opts.max !== undefined ? Number(opts.max) : undefined,
        inferTicket: opts.inferTicket !== false,
      },
    };
    const passCache = opts.cache === false ? undefined : new PassCache(passCacheDir(store.storeDir));
    const deps = {
      generate: (t: CommitTask) =>
        generateLesson({
          cwd: store.cwd,
          fromRef: t.parent ?? EMPTY_TREE,
          toRef: t.sha,
          ticketId: t.ticketId ?? undefined,
          modelFile: opts.modelFile,
          modelSynth: opts.modelSynth,
          concurrency: Number(opts.concurrency) || 4,
          profile,
          passCache,
          onProgress: (m: string) => log.debug(m),
        }),
      save: (b: Parameters<typeof saveLesson>[0]) => saveLesson(b, store.lessonsDir),
      log,
    };

    // SIGINT #1: finish the in-flight lesson (minutes of paid work — never
    // throw it away); SIGINT #2: abandon and exit 130.
    const controller = new AbortController();
    let interrupts = 0;
    const onSignal = () => {
      interrupts += 1;
      if (interrupts === 1) {
        log.warn("stopping — finishing the current lesson first (Ctrl-C again to abort)");
        controller.abort();
      } else {
        log.error("aborted by signal");
        releaseLock(store.storeDir).finally(() => process.exit(130));
      }
    };
    process.on("SIGINT", onSignal);
    process.on("SIGTERM", onSignal);

    try {
      if (opts.once) {
        const summary = await runOnce(runOpts, deps);
        log.info(`done: ${summary.processed} taught · ${summary.failed} failed · ${summary.skipped} skipped`);
        if (summary.failed > 0 || summary.refused) process.exitCode = 1;
      } else {
        await runDaemon(runOpts, deps, controller.signal);
      }
    } finally {
      await releaseLock(store.storeDir);
    }
  });

program.parseAsync(process.argv).catch((err) => {
  console.error(`\ngandalf: ${err instanceof Error ? err.message : String(err)}`);
  process.exitCode = 1;
});
