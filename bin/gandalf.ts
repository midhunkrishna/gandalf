#!/usr/bin/env -S npx tsx
import { Command } from "commander";
import { resolve } from "node:path";
import { repoRoot } from "../src/core/git.ts";
import { generateLesson } from "../src/core/pipeline.ts";
import {
  saveLesson,
  listLessons,
  defaultLessonsDir,
} from "../src/core/lesson.ts";
import { startServer, webBuilt } from "../src/server/serve.ts";

const program = new Command();

program
  .name("gandalf")
  .description("Teaches the code changes behind each commit/ticket — generated by Claude Code.")
  .version("0.0.0");

program
  .command("generate")
  .description("Analyze a diff and write a lesson bundle (default: HEAD vs working tree).")
  .option("--from <ref>", "base ref", "HEAD")
  .option("--to <ref>", "target ref (omit for the uncommitted working tree)")
  .option("--ticket <id>", "force a ticket id for the intent overlay")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory (default: <repo>/.gandalf/lessons)")
  .option("--model-file <model>", "model for per-file passes", "sonnet")
  .option("--model-synth <model>", "model for the synthesis pass", "opus")
  .option("--concurrency <n>", "parallel per-file passes", "4")
  .action(async (opts) => {
    const cwd = await repoRoot(resolve(opts.cwd));
    const bundle = await generateLesson({
      cwd,
      fromRef: opts.from,
      toRef: opts.to, // undefined -> working tree
      ticketId: opts.ticket,
      modelFile: opts.modelFile,
      modelSynth: opts.modelSynth,
      concurrency: Number(opts.concurrency) || 4,
      onProgress: (m) => process.stderr.write(`${m}\n`),
    });
    const lessonsDir = opts.outDir ? resolve(opts.outDir) : defaultLessonsDir(cwd);
    const file = await saveLesson(bundle, lessonsDir);
    process.stderr.write("\n");
    console.log(`Lesson: ${bundle.meta.title}`);
    console.log(`  verdict: ${bundle.meta.verdict}  breaking: ${bundle.meta.breakingCount}`);
    console.log(`  files: ${bundle.files.length}  contracts: ${bundle.contracts.length}`);
    console.log(`  saved: ${file}`);
  });

program
  .command("list")
  .description("List persisted lessons (newest first).")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory")
  .action(async (opts) => {
    const cwd = await repoRoot(resolve(opts.cwd));
    const lessonsDir = opts.outDir ? resolve(opts.outDir) : defaultLessonsDir(cwd);
    const metas = await listLessons(lessonsDir);
    if (!metas.length) {
      console.log("No lessons yet.");
      return;
    }
    for (const m of metas) {
      console.log(`${m.createdAt}  ${m.id}`);
      console.log(`    ${m.title}  [${m.verdict}${m.breakingCount ? `, ${m.breakingCount} breaking` : ""}]`);
    }
  });

program
  .command("serve")
  .description("Serve the interactive viewer + lesson API.")
  .option("--cwd <dir>", "repository directory", process.cwd())
  .option("--out-dir <dir>", "lessons directory")
  .option("--port <n>", "port", "4173")
  .action(async (opts) => {
    const cwd = await repoRoot(resolve(opts.cwd));
    const lessonsDir = opts.outDir ? resolve(opts.outDir) : defaultLessonsDir(cwd);
    if (!webBuilt()) {
      console.error("Viewer not built yet. Run: npm run build:web");
      process.exitCode = 1;
      return;
    }
    await startServer({ lessonsDir, port: Number(opts.port) || 4173 });
  });

program
  .command("build")
  .description("Export a self-contained static HTML lesson (Phase 4).")
  .action(() => {
    console.error("`gandalf build` arrives in Phase 4 (vite-plugin-singlefile export).");
    process.exitCode = 1;
  });

program.parseAsync(process.argv).catch((err) => {
  console.error(`\ngandalf: ${err instanceof Error ? err.message : String(err)}`);
  process.exitCode = 1;
});
